/**
 * Generated Function resources
 *
 * @remarks
 * Contains all Azure Functions infrastructure and code artifacts generated by the synthesizer:
 * - **functionApp**: The Azure Function App (L2 CDK construct)
 * - **appServicePlan**: The App Service Plan hosting the Function App (L2 CDK construct)
 * - **functions**: Array of individual function definitions with metadata
 *
 * Each CRUD model generates 5 functions following REST conventions:
 * - GET /resources (list)
 * - POST /resources (create)
 * - GET /resources/{id} (get)
 * - PUT /resources/{id} (update)
 * - DELETE /resources/{id} (delete)
 *
 * @example
 * ```typescript
 * const resources: FunctionResources = {
 *   functionApp: functionAppSite,
 *   appServicePlan: plan,
 *   functions: [
 *     {
 *       name: 'list-users',
 *       type: 'list',
 *       modelName: 'User',
 *       httpTrigger: { methods: ['GET'], route: 'users', authLevel: 'function' },
 *       cosmosBinding: { connection: 'CosmosDB', databaseName: 'myapp', containerName: 'users' },
 *       template: { language: 'typescript', templateType: 'crud', sourceCode: '...' }
 *     },
 *     // ... 4 more functions for User model
 *   ]
 * };
 * ```
 */
export interface FunctionResources {
  /**
   * Function App resource (L2 construct)
   *
   * @remarks
   * The Azure Function App (Sites resource with kind 'functionapp') that hosts all function code.
   * Configured with runtime settings, app settings, and managed identity.
   *
   * **Null in Placeholder Implementations:**
   * May be null during incremental development phases. Check before using.
   *
   * Use this to:
   * - Grant access to other Azure resources (Cosmos DB, Storage, etc.)
   * - Get the function app URL for API integration
   * - Add additional app settings or connection strings
   * - Configure deployment settings
   *
   * This is the ISite interface from @atakora/cdk/web, representing a Function App
   * (which is technically a specialized App Service).
   */
  readonly functionApp: ISite | null;

  /**
   * App Service Plan resource (L2 construct)
   *
   * @remarks
   * The hosting plan for the Function App. Defines the compute resources,
   * scaling behavior, and pricing tier.
   *
   * **Null in Placeholder Implementations:**
   * May be null during incremental development phases. Check before using.
   *
   * **Common SKUs:**
   * - **Y1** (Consumption): Pay-per-execution, auto-scale, 1.5GB memory
   * - **EP1** (Elastic Premium): Pre-warmed instances, VNet integration, 3.5GB memory
   * - **EP2** (Elastic Premium): Pre-warmed instances, VNet integration, 7GB memory
   * - **EP3** (Elastic Premium): Pre-warmed instances, VNet integration, 14GB memory
   *
   * Use this to:
   * - Scale out instances
   * - Configure auto-scale rules
   * - Enable zone redundancy
   * - Reference in other Function Apps (shared plan)
   */
  readonly appServicePlan: IServerFarm | null;

  /**
   * Individual function definitions
   *
   * @remarks
   * Array of all functions generated for the schema, including:
   * - CRUD operation functions (5 per model)
   * - Custom function models
   * - Event handler functions
   *
   * Each definition includes:
   * - Function metadata (name, type, model)
   * - HTTP trigger configuration
   * - Cosmos DB bindings (if applicable)
   * - Generated TypeScript source code template
   *
   * Use this to:
   * - Generate function.json files during deployment
   * - Write function handler TypeScript files
   * - Configure routing and authorization
   * - Track function inventory for documentation
   *
   * The functions array is ordered by model name and operation type for consistency.
   */
  readonly functions: readonly FunctionDefinition[];
}

