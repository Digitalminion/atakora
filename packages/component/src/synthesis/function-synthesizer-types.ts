/**
 * Function code template
 *
 * @remarks
 * Contains the generated source code and metadata for a function.
 * Used during synthesis to create deployable function code.
 *
 * **Template Generation:**
 * 1. Synthesizer generates TypeScript code from templates
 * 2. Code includes imports, handler function, business logic
 * 3. Error handling and logging are built-in
 * 4. Dependencies are tracked for package.json generation
 *
 * **Deployment:**
 * - Source code is written to `functions/{functionName}/index.ts`
 * - Dependencies are aggregated into root `package.json`
 * - Code is compiled to JavaScript for deployment
 *
 * @example
 * CRUD template for get operation:
 * ```typescript
 * const template: FunctionTemplate = {
 *   language: 'typescript',
 *   templateType: 'crud',
 *   sourceCode: `
 *     import { AzureFunction, Context, HttpRequest } from '@azure/functions';
 *     import { CosmosClient } from '@azure/cosmos';
 *
 *     const handler: AzureFunction = async (context: Context, req: HttpRequest) => {
 *       const { id } = context.bindingData;
 *       const client = new CosmosClient(process.env.CosmosDB);
 *       const container = client.database('myapp').container('users');
 *       const { resource } = await container.item(id, id).read();
 *       context.res = { status: 200, body: resource };
 *     };
 *
 *     export default handler;
 *   `,
 *   dependencies: {
 *     '@azure/functions': '^4.0.0',
 *     '@azure/cosmos': '^4.0.0'
 *   }
 * };
 * ```
 */
export interface FunctionTemplate {
  /**
   * Programming language
   *
   * @remarks
   * The language of the generated code.
   *
   * **Supported Languages:**
   * - **typescript**: TypeScript (primary, recommended)
   * - **javascript**: JavaScript (for legacy support)
   *
   * **Default**: 'typescript'
   *
   * TypeScript is recommended for type safety, better IDE support,
   * and alignment with the component library's TypeScript-first approach.
   */
  readonly language: 'typescript' | 'javascript';

  /**
   * Template type
   *
   * @remarks
   * Indicates the template pattern used for code generation.
   *
   * **Template Types:**
   * - **crud**: Standard CRUD operation (get, list, create, update, delete)
   * - **custom**: Custom function logic from schema function models
   *
   * CRUD templates follow a standard pattern with error handling,
   * validation, and Cosmos DB integration.
   *
   * Custom templates are more flexible and may include different logic.
   */
  readonly templateType: 'crud' | 'custom';

  /**
   * Generated source code
   *
   * @remarks
   * The complete TypeScript or JavaScript source code for the function.
   * Includes:
   * - Import statements
   * - Handler function declaration
   * - Business logic (CRUD operations, custom logic)
   * - Error handling
   * - Logging statements
   * - Response formatting
   *
   * **Code Structure:**
   * ```typescript
   * // Imports
   * import { AzureFunction, Context, HttpRequest } from '@azure/functions';
   * import { CosmosClient } from '@azure/cosmos';
   *
   * // Handler
   * const handler: AzureFunction = async (context: Context, req: HttpRequest) => {
   *   // Business logic
   *   context.res = { status: 200, body: result };
   * };
   *
   * // Export
   * export default handler;
   * ```
   *
   * The source code is written to `functions/{functionName}/index.ts` during deployment.
   */
  readonly sourceCode: string;

  /**
   * npm package dependencies (optional)
   *
   * @remarks
   * Map of package names to version specifiers required by the function.
   * These dependencies are aggregated across all functions and written
   * to the root `package.json` of the deployment package.
   *
   * **Common Dependencies:**
   * - `@azure/functions`: Azure Functions runtime and types
   * - `@azure/cosmos`: Cosmos DB client SDK
   * - `@azure/identity`: Azure authentication
   * - `@azure/storage-blob`: Blob storage client
   * - `zod`: Runtime validation
   *
   * **Version Specifiers:**
   * - Exact: `'4.0.0'`
   * - Caret: `'^4.0.0'` (recommended, allows patch/minor updates)
   * - Tilde: `'~4.0.0'` (allows patch updates only)
   *
   * @example
   * ```typescript
   * dependencies: {
   *   '@azure/functions': '^4.0.0',
   *   '@azure/cosmos': '^4.0.0',
   *   '@azure/identity': '^3.1.0',
   *   'zod': '^3.22.0'
   * }
   * ```
   */
  readonly dependencies?: Record<string, string>;
}
