// Cosmos DB Binding Configuration
// ============================================================================

/**
 * Cosmos DB binding configuration for Azure Functions
 *
 * @remarks
 * Configures input/output bindings to Cosmos DB for data operations.
 * The binding allows functions to read and write documents without
 * explicitly managing the Cosmos DB client.
 *
 * **Binding Types:**
 * - **Input Binding**: Read documents (for get, list operations)
 * - **Output Binding**: Write documents (for create, update, delete operations)
 *
 * The binding direction is inferred from the function type:
 * - get, list → input binding
 * - create, update, delete → output binding
 *
 * @example
 * Input binding for get operation:
 * ```typescript
 * const binding: CosmosBindingConfig = {
 *   connection: 'CosmosDB',
 *   databaseName: 'myapp',
 *   containerName: 'users'
 * };
 * ```
 *
 * Generates function.json:
 * ```json
 * {
 *   "type": "cosmosDB",
 *   "direction": "in",
 *   "name": "inputDocument",
 *   "connectionStringSetting": "CosmosDB",
 *   "databaseName": "myapp",
 *   "collectionName": "users",
 *   "id": "{id}",
 *   "partitionKey": "{id}"
 * }
 * ```
 */
export interface CosmosBindingConfig {
  /**
   * Connection string setting name
   *
   * @remarks
   * Name of the app setting containing the Cosmos DB connection string.
   * The Function App's application settings will have an entry like:
   * - `CosmosDB`: `AccountEndpoint=https://...;AccountKey=...;`
   *
   * **Convention**: Use 'CosmosDB' as the standard connection setting name.
   *
   * **Security**: Connection strings are stored as app settings (encrypted at rest).
   * For enhanced security, use Key Vault references:
   * - `@Microsoft.KeyVault(SecretUri=https://myvault.vault.azure.net/secrets/cosmos-connection)`
   *
   * @default 'CosmosDB'
   */
  readonly connection: string;

  /**
   * Cosmos DB database name
   *
   * @remarks
   * The name of the database containing the target container.
   * Typically matches the project or application name.
   *
   * **Example**: 'myapp', 'myapp-db', 'production-db'
   */
  readonly databaseName: string;

  /**
   * Cosmos DB container name
   *
   * @remarks
   * The name of the container (collection) to read from or write to.
   * Typically the pluralized, lowercase model name.
   *
   * **Naming Convention**: Pluralize and lowercase the model name
   * - Model 'User' → Container 'users'
   * - Model 'Product' → Container 'products'
   * - Model 'Order' → Container 'orders'
   *
   * **Example**: 'users', 'products', 'orders', 'invoices'
   */
  readonly containerName: string;
}

