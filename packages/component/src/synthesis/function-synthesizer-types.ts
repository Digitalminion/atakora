// Function Synthesizer Interface
// ============================================================================

/**
 * Interface for Function Synthesizer
 *
 * @remarks
 * The FunctionSynthesizer generates Azure Functions resources and code from schema definitions.
 * It creates serverless compute infrastructure and TypeScript function handlers for:
 * - CRUD operations for each model (5 functions per model: get, list, create, update, delete)
 * - Custom function models defined in the schema
 * - Event handlers for event models
 *
 * The synthesizer orchestrates:
 * 1. App Service Plan creation (hosting infrastructure)
 * 2. Function App creation (runtime environment)
 * 3. Function code generation (TypeScript handlers)
 * 4. Cosmos DB bindings configuration
 * 5. Application settings and environment variables
 *
 * @example
 * ```typescript
 * const synthesizer = new FunctionSynthesizer();
 * const resources = await synthesizer.synthesize(
 *   schema,
 *   stack,
 *   dataResources,
 *   apiResources
 * );
 *
 * // Access generated resources
 * console.log(resources.functionApp.siteName);
 * console.log(resources.functions.length); // 5 per CRUD model
 * ```
 */
export interface FunctionSynthesizer {
  /**
   * Synthesize Azure Functions resources from schema
   *
   * @param schema - Schema object containing model definitions
   * @param stack - Resource group stack for CDK construct placement
   * @param dataResources - Cosmos DB resources for data layer integration
   * @param apiResources - API Management resources for API layer integration
   * @returns Promise resolving to generated function resources
   *
   * @throws {Error} If schema validation fails
   * @throws {Error} If function app configuration is invalid
   * @throws {Error} If code generation fails
   *
   * @remarks
   * The synthesize method performs the following phases:
   * 1. **Discovery**: Analyze schema to identify CRUD models, function models, and event models
   * 2. **Infrastructure**: Create App Service Plan and Function App
   * 3. **Code Generation**: Generate TypeScript function handlers for each operation
   * 4. **Bindings**: Configure Cosmos DB input/output bindings
   * 5. **Configuration**: Set application settings, connection strings, and environment variables
   * 6. **Validation**: Ensure all resources and code are valid and deployable
   */
  synthesize(
    schema: SchemaObject,
    stack: ResourceGroupStack,
    dataResources: DataResources,
    apiResources: ApiResources
  ): Promise<FunctionResources>;
}

