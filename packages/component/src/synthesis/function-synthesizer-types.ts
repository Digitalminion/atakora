/**
 * Individual function definition
 *
 * @remarks
 * Represents a single Azure Function with its configuration and generated code.
 * Each function includes HTTP trigger configuration, optional Cosmos DB bindings,
 * and a TypeScript code template.
 *
 * **Function Types:**
 * - **get**: Retrieve single resource by ID (GET /resources/{id})
 * - **list**: Retrieve collection of resources (GET /resources)
 * - **create**: Create new resource (POST /resources)
 * - **update**: Update existing resource (PUT /resources/{id})
 * - **delete**: Delete resource (DELETE /resources/{id})
 * - **custom**: Custom function logic (defined in schema)
 *
 * @example
 * CRUD function for User model:
 * ```typescript
 * const func: FunctionDefinition = {
 *   name: 'get-user',
 *   type: 'get',
 *   modelName: 'User',
 *   httpTrigger: {
 *     methods: ['GET'],
 *     route: 'users/{id}',
 *     authLevel: 'function'
 *   },
 *   cosmosBinding: {
 *     connection: 'CosmosDB',
 *     databaseName: 'myapp',
 *     containerName: 'users'
 *   },
 *   template: {
 *     language: 'typescript',
 *     templateType: 'crud',
 *     sourceCode: 'export async function handler(...) { ... }',
 *     dependencies: {
 *       '@azure/cosmos': '^4.0.0'
 *     }
 *   }
 * };
 * ```
 */
export interface FunctionDefinition {
  /**
   * Function name
   *
   * @remarks
   * Unique identifier for the function. Used for:
   * - Function folder name (e.g., `functions/get-user/`)
   * - Function.json file location
   * - Logging and telemetry
   * - Azure portal display name
   *
   * **Naming Convention**: `{operation}-{model-name}`
   * - Examples: `get-user`, `list-products`, `create-order`, `update-invoice`, `delete-comment`
   *
   * **Constraints:**
   * - Lowercase letters, numbers, and hyphens only
   * - Must be unique within the Function App
   * - Recommended: 2-50 characters
   */
  readonly name: string;

  /**
   * Function type/operation
   *
   * @remarks
   * Indicates the operation this function performs.
   * Determines the HTTP method, route pattern, and code template.
   *
   * **CRUD Types:**
   * - **get**: Retrieve single resource by ID
   * - **list**: Retrieve collection of resources
   * - **create**: Create new resource
   * - **update**: Update existing resource
   * - **delete**: Delete resource
   *
   * **Custom Type:**
   * - **custom**: Custom logic defined in schema function models
   */
  readonly type: 'get' | 'list' | 'create' | 'update' | 'delete' | 'custom';

  /**
   * Associated model name
   *
   * @remarks
   * The schema model this function operates on.
   * For CRUD operations, this is the CRUD model name (e.g., 'User', 'Product').
   * For custom functions, this may be a descriptive name.
   *
   * Used for:
   * - Determining Cosmos DB container name
   * - Generating function code
   * - API documentation
   *
   * **Example**: 'User', 'Product', 'Order', 'Invoice'
   */
  readonly modelName: string;

  /**
   * HTTP trigger configuration
   *
   * @remarks
   * Defines how the function is triggered via HTTP requests.
   * Includes allowed methods, route pattern, and authorization level.
   *
   * **Route Patterns:**
   * - Collection: `users` (for list, create)
   * - Resource: `users/{id}` (for get, update, delete)
   * - Nested: `users/{userId}/posts/{postId}`
   *
   * **Auth Levels:**
   * - **anonymous**: No authentication required (not recommended)
   * - **function**: Requires function key in query string or header
   * - **admin**: Requires master key (host-level access)
   *
   * For production, use 'function' level and delegate authentication to API Management.
   */
  readonly httpTrigger: HttpTriggerConfig;

  /**
   * Cosmos DB binding configuration (optional)
   *
   * @remarks
   * Configures input/output bindings to Cosmos DB for data access.
   * Only applicable to CRUD functions that interact with Cosmos DB.
   *
   * Custom functions may not have Cosmos DB bindings if they don't access data.
   *
   * **Binding Modes:**
   * - Input binding: Read documents (for get, list)
   * - Output binding: Write documents (for create, update, delete)
   *
   * The binding configuration is used to generate the `bindings` array in function.json.
   */
  readonly cosmosBinding?: CosmosBindingConfig;

  /**
   * Function code template
   *
   * @remarks
   * Contains the generated TypeScript source code for the function handler.
   * Includes imports, handler function, and business logic.
   *
   * The template is rendered during synthesis and written to the function's
   * index.ts file in the deployment package.
   *
   * **Template Types:**
   * - **crud**: Standard CRUD operation template (get, list, create, update, delete)
   * - **custom**: Custom logic template for function models
   *
   * Templates include error handling, logging, and Cosmos DB client initialization.
   */
  readonly template: FunctionTemplate;
}

