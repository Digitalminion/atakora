/**
 * HTTP trigger configuration for Azure Functions
 *
 * @remarks
 * Defines how a function responds to HTTP requests.
 * Maps to the HTTP trigger binding in function.json.
 *
 * @example
 * GET endpoint:
 * ```typescript
 * const trigger: HttpTriggerConfig = {
 *   methods: ['GET'],
 *   route: 'users/{id}',
 *   authLevel: 'function'
 * };
 * ```
 *
 * @example
 * POST endpoint:
 * ```typescript
 * const trigger: HttpTriggerConfig = {
 *   methods: ['POST'],
 *   route: 'users',
 *   authLevel: 'function'
 * };
 * ```
 */
export interface HttpTriggerConfig {
  /**
   * Allowed HTTP methods
   *
   * @remarks
   * Array of HTTP methods that can trigger this function.
   * Functions typically accept a single method, but multiple methods are supported.
   *
   * **Standard CRUD Mapping:**
   * - GET: Retrieve (get, list)
   * - POST: Create
   * - PUT: Update (full replacement)
   * - PATCH: Update (partial)
   * - DELETE: Delete
   *
   * **Examples:**
   * - `['GET']` - Read-only endpoint
   * - `['POST']` - Create endpoint
   * - `['PUT', 'PATCH']` - Update endpoint supporting both methods
   */
  readonly methods: readonly ('GET' | 'POST' | 'PUT' | 'DELETE' | 'PATCH')[];

  /**
   * URL route pattern
   *
   * @remarks
   * The route template for the function endpoint.
   * Relative to the Function App base URL.
   *
   * **Route Parameters:**
   * - Enclosed in curly braces: `{paramName}`
   * - Accessible in function code via `context.bindingData.paramName`
   * - Can include multiple parameters: `users/{userId}/posts/{postId}`
   *
   * **Examples:**
   * - `users` - Collection endpoint
   * - `users/{id}` - Resource endpoint with ID parameter
   * - `users/{userId}/orders/{orderId}` - Nested resource
   *
   * **Note**: Do not include leading slash. Azure Functions adds it automatically.
   */
  readonly route: string;

  /**
   * Authorization level
   *
   * @remarks
   * Determines what level of authentication is required to invoke the function.
   *
   * **Levels:**
   * - **anonymous**: No key required (public endpoint)
   * - **function**: Function-specific key required
   * - **admin**: Master (host) key required
   *
   * **Recommendations:**
   * - Development: 'function' or 'anonymous' (for testing)
   * - Production: 'function' with API Management handling authentication
   * - Internal admin endpoints: 'admin'
   *
   * **Security Note**: 'anonymous' should only be used for truly public endpoints.
   * For production APIs, use 'function' level and delegate auth to API Management.
   *
   * @default 'function'
   */
  readonly authLevel?: 'anonymous' | 'function' | 'admin';
}

