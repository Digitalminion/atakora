/**
 * Function App configuration
 *
 * @remarks
 * Configuration options for the Azure Function App.
 * Provides sensible defaults while allowing customization for different environments.
 *
 * **Default Behavior:**
 * - Runtime: Node.js (based on generated TypeScript code)
 * - Runtime Version: 18 (LTS)
 * - SKU: Y1 Consumption (development), EP1 (production)
 * - Always On: false (Consumption), true (Premium)
 *
 * @example
 * Development configuration:
 * ```typescript
 * const config: FunctionConfiguration = {
 *   appName: 'func-myapp-dev-eus-01',
 *   runtime: 'node',
 *   runtimeVersion: '18',
 *   sku: 'Y1',
 *   alwaysOn: false
 * };
 * ```
 *
 * @example
 * Production configuration with Premium plan:
 * ```typescript
 * const config: FunctionConfiguration = {
 *   appName: 'func-myapp-prod-eus-01',
 *   runtime: 'node',
 *   runtimeVersion: '18',
 *   sku: 'EP1',
 *   alwaysOn: true,
 *   appSettings: {
 *     'WEBSITE_RUN_FROM_PACKAGE': '1',
 *     'FUNCTIONS_WORKER_RUNTIME': 'node',
 *     'NODE_ENV': 'production'
 *   }
 * };
 * ```
 */
export interface FunctionConfiguration {
  /**
   * Function App name (optional - auto-generated if not provided)
   *
   * @remarks
   * Must be globally unique across all of Azure.
   *
   * **Constraints:**
   * - 2-60 characters
   * - Alphanumeric and hyphens only
   * - Cannot start or end with hyphen
   * - Globally unique (creates {appName}.azurewebsites.net)
   *
   * **Pattern**: `^[a-zA-Z0-9][a-zA-Z0-9-]{0,58}[a-zA-Z0-9]$`
   *
   * If not provided, a name will be generated using the project naming convention:
   * - Format: `func-{project}-{env}-{geo}-{instance}`
   * - Example: `func-myapp-dev-eus-01`
   */
  readonly appName?: string;

  /**
   * Function runtime (optional - defaults to 'node')
   *
   * @remarks
   * The language runtime for Azure Functions.
   *
   * **Supported Runtimes:**
   * - **node**: Node.js (for TypeScript/JavaScript)
   * - **python**: Python
   * - **dotnet**: .NET (C#/F#)
   *
   * **Default**: 'node' (since we generate TypeScript code)
   */
  readonly runtime?: 'node' | 'python' | 'dotnet';

  /**
   * Runtime version (optional - defaults based on runtime)
   *
   * @remarks
   * The version of the runtime to use.
   *
   * **Node.js versions:**
   * - '18' (LTS, recommended)
   * - '16' (LTS)
   * - '14' (legacy)
   *
   * **Python versions:**
   * - '3.11'
   * - '3.10'
   * - '3.9'
   *
   * **.NET versions:**
   * - '8.0' (LTS)
   * - '6.0' (LTS)
   *
   * **Default**: '18' for node, '3.11' for python, '8.0' for dotnet
   */
  readonly runtimeVersion?: string;

  /**
   * App Service Plan SKU (optional - defaults based on environment)
   *
   * @remarks
   * Determines the hosting plan and pricing tier.
   *
   * **SKU Options:**
   * - **Y1** (Consumption): Pay-per-execution, dynamic scaling, 1.5GB memory, 5-10 min timeout
   * - **EP1** (Elastic Premium): Always ready instances, VNet, 3.5GB memory, unlimited timeout
   * - **EP2** (Elastic Premium): Always ready instances, VNet, 7GB memory, unlimited timeout
   * - **EP3** (Elastic Premium): Always ready instances, VNet, 14GB memory, unlimited timeout
   *
   * **Default**: 'Y1' for development, 'EP1' for production
   *
   * **Note**: Consumption (Y1) cannot use alwaysOn=true. Premium plans (EP*) support VNet integration.
   */
  readonly sku?: 'Y1' | 'EP1' | 'EP2' | 'EP3';

  /**
   * Always On setting (optional - defaults based on SKU)
   *
   * @remarks
   * Keeps the Function App loaded even when idle.
   * Prevents cold starts but increases cost.
   *
   * **Constraints:**
   * - Must be false for Consumption (Y1) plans
   * - Recommended true for Premium (EP*) plans
   * - Recommended true for production workloads on Premium plans
   *
   * **Default**: false for Y1, true for EP*
   */
  readonly alwaysOn?: boolean;

  /**
   * Application settings (optional)
   *
   * @remarks
   * Environment variables and configuration settings for the Function App.
   * Merged with auto-generated settings (Cosmos DB connection strings, etc.).
   *
   * **Common Settings:**
   * - `WEBSITE_RUN_FROM_PACKAGE`: '1' (run from deployment package)
   * - `FUNCTIONS_WORKER_RUNTIME`: Runtime identifier
   * - `NODE_ENV`: 'production' or 'development'
   * - `APPINSIGHTS_INSTRUMENTATIONKEY`: Application Insights key
   *
   * **Auto-generated Settings:**
   * - `CosmosDB__connectionString`: Cosmos DB connection string
   * - `CosmosDB__databaseName`: Database name
   * - `FUNCTIONS_EXTENSION_VERSION`: '~4'
   *
   * Custom settings override auto-generated settings with the same key.
   *
   * @example
   * ```typescript
   * appSettings: {
   *   'NODE_ENV': 'production',
   *   'LOG_LEVEL': 'info',
   *   'CUSTOM_API_KEY': '@Microsoft.KeyVault(SecretUri=...)'
   * }
   * ```
   */
  readonly appSettings?: Record<string, string>;
}

