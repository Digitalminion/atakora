// Policy Type Definitions
// ============================================================================

/**
 * Rate limiting policy configuration
 *
 * @remarks
 * Controls the rate at which API calls can be made.
 * Prevents abuse and ensures service availability.
 *
 * @example
 * ```typescript
 * const rateLimit: RateLimitPolicy = {
 *   calls: 100,        // 100 calls
 *   renewalPeriod: 60  // per 60 seconds
 * };
 * ```
 */
export interface RateLimitPolicy {
  /**
   * Maximum number of calls allowed
   *
   * @remarks
   * Number of API calls permitted within the renewal period.
   */
  readonly calls: number;

  /**
   * Time window in seconds
   *
   * @remarks
   * Duration of the rate limit window in seconds.
   * After this period, the call counter resets.
   *
   * **Common Values:**
   * - 60 (1 minute)
   * - 3600 (1 hour)
   * - 86400 (1 day)
   */
  readonly renewalPeriod: number;

  /**
   * Counter key
   *
   * @remarks
   * Identifies the counter scope (per subscription, per IP, etc.)
   *
   * **Default**: Per subscription key
   */
  readonly counterKey?: string;
}

/**
 * Authentication policy configuration
 *
 * @remarks
 * Validates authentication tokens and enforces access control.
 * Supports multiple authentication schemes common in Azure.
 *
 * @example
 * OAuth2/JWT:
 * ```typescript
 * const auth: AuthenticationPolicy = {
 *   type: 'jwt',
 *   config: {
 *     issuer: 'https://login.microsoftonline.com/{tenantId}',
 *     audience: 'api://my-api',
 *     requiredClaims: ['scope']
 *   }
 * };
 * ```
 *
 * @example
 * API Key:
 * ```typescript
 * const auth: AuthenticationPolicy = {
 *   type: 'apiKey',
 *   config: {
 *     headerName: 'X-API-Key',
 *     paramName: 'api_key'
 *   }
 * };
 * ```
 */
export interface AuthenticationPolicy {
  /**
   * Authentication type
   *
   * @remarks
   * - **oauth2**: OAuth 2.0 / OpenID Connect
   * - **apiKey**: Subscription key or custom API key
   * - **jwt**: JWT token validation
   * - **certificate**: Client certificate authentication
   */
  readonly type: 'oauth2' | 'apiKey' | 'jwt' | 'certificate';

  /**
   * Type-specific configuration
   *
   * @remarks
   * Configuration schema varies by authentication type.
   * See specific type examples for structure.
   */
  readonly config: Record<string, any>;
}

/**
 * CORS policy configuration
 *
 * @remarks
 * Configures Cross-Origin Resource Sharing headers.
 * Required for browser-based single-page applications.
 *
 * @example
 * ```typescript
 * const cors: CorsPolicy = {
 *   allowedOrigins: ['https://app.example.com', 'https://admin.example.com'],
 *   allowedMethods: ['GET', 'POST', 'PUT', 'DELETE'],
 *   allowedHeaders: ['Content-Type', 'Authorization'],
 *   exposeHeaders: ['X-Request-Id'],
 *   allowCredentials: true,
 *   maxAge: 3600
 * };
 * ```
 */
export interface CorsPolicy {
  /**
   * Allowed origin domains
   *
   * @remarks
   * Array of allowed origins or '*' for all origins.
   *
   * **Security Warning**: Avoid using '*' in production.
   * Always specify explicit origins for security.
   *
   * **Examples:**
   * - `['https://app.example.com']`
   * - `['https://*.example.com']` (wildcard subdomain)
   */
  readonly allowedOrigins: readonly string[];

  /**
   * Allowed HTTP methods
   *
   * @remarks
   * Array of HTTP methods permitted for CORS requests.
   *
   * **Common**: `['GET', 'POST', 'PUT', 'DELETE', 'PATCH']`
   */
  readonly allowedMethods: readonly string[];

  /**
   * Allowed request headers
   *
   * @remarks
   * Headers that clients can include in CORS requests.
   *
   * **Common**: `['Content-Type', 'Authorization', 'X-Request-Id']`
   */
  readonly allowedHeaders?: readonly string[];

  /**
   * Exposed response headers
   *
   * @remarks
   * Headers that browsers can access in CORS responses.
   *
   * **Common**: `['X-Request-Id', 'X-Total-Count']`
   */
  readonly exposeHeaders?: readonly string[];

  /**
   * Allow credentials (cookies, auth headers)
   *
   * @remarks
   * If true, allows cookies and authentication headers in CORS requests.
   *
   * **Default**: false
   */
  readonly allowCredentials?: boolean;

  /**
   * Preflight cache duration in seconds
   *
   * @remarks
   * How long browsers should cache CORS preflight responses.
   *
   * **Default**: 3600 (1 hour)
   */
  readonly maxAge?: number;
}

/**
 * IP filtering policy configuration
 *
 * @remarks
 * Restricts API access based on client IP address.
 * Useful for internal APIs or partner integrations.
 *
 * @example
 * ```typescript
 * const ipFilter: IpFilterPolicy = {
 *   mode: 'allow',
 *   addresses: ['203.0.113.0/24', '198.51.100.42']
 * };
 * ```
 */
export interface IpFilterPolicy {
  /**
   * Filter mode
   *
   * @remarks
   * - **allow**: Only listed IPs can access (whitelist)
   * - **deny**: Listed IPs are blocked (blacklist)
   */
  readonly mode: 'allow' | 'deny';

  /**
   * IP addresses or CIDR ranges
   *
   * @remarks
   * Array of IP addresses or CIDR notation ranges.
   *
   * **Examples:**
   * - `'203.0.113.42'` (single IP)
   * - `'203.0.113.0/24'` (CIDR range)
   */
  readonly addresses: readonly string[];
}

/**
 * Caching policy configuration
 *
 * @remarks
 * Configures response caching for GET operations.
 * Improves performance and reduces backend load.
 *
 * **Note**: Only applicable to GET operations with successful responses (200-299).
 *
 * @example
 * ```typescript
 * const caching: CachingPolicy = {
 *   duration: 300,              // Cache for 5 minutes
 *   varyByHeaders: ['Accept'],  // Vary cache by Accept header
 *   varyByQueryParams: ['page'] // Vary cache by page param
 * };
 * ```
 */
export interface CachingPolicy {
  /**
   * Cache duration in seconds
   *
   * @remarks
   * How long responses should be cached.
   *
   * **Common Values:**
   * - 60 (1 minute)
   * - 300 (5 minutes)
   * - 3600 (1 hour)
   */
  readonly duration: number;

  /**
   * Vary cache by request headers
   *
   * @remarks
   * Cache separate responses for different header values.
   *
   * **Example**: `['Accept', 'Accept-Language']`
   */
  readonly varyByHeaders?: readonly string[];

  /**
   * Vary cache by query parameters
   *
   * @remarks
   * Cache separate responses for different query parameter values.
   *
   * **Example**: `['page', 'limit', 'sort']`
   */
  readonly varyByQueryParams?: readonly string[];

  /**
   * Cache responses per subscription
   *
   * @remarks
   * If true, each subscription gets its own cache.
   *
   * **Default**: false
   */
  readonly varyBySubscription?: boolean;
}
