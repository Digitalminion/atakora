/**
 * API Management service configuration
 *
 * @remarks
 * Configuration for the Azure API Management service instance.
 * Provides sensible defaults for common scenarios while allowing customization.
 *
 * **Default Behavior:**
 * - SKU: Developer (non-prod), Consumption (production)
 * - Publisher: Derived from backend settings
 * - Location: Same as resource group
 *
 * @example
 * ```typescript
 * const config: ApiConfiguration = {
 *   serviceName: 'apim-myapp-dev-eus-01',
 *   sku: 'Developer',
 *   publisherEmail: 'api@example.com',
 *   publisherName: 'My Company'
 * };
 * ```
 */
export interface ApiConfiguration {
  /**
   * API Management service name
   *
   * @remarks
   * Must be globally unique across Azure.
   * If not provided, will be auto-generated using naming conventions.
   *
   * **Format**: `apim-{org}-{project}-{env}-{geo}-{instance}`
   *
   * **Constraints:**
   * - 1-50 characters
   * - Alphanumeric and hyphens only
   * - Must start with letter
   * - Must end with alphanumeric
   */
  readonly serviceName?: string;

  /**
   * API Management SKU
   *
   * @remarks
   * **SKU Options:**
   * - **Consumption**: Pay-per-use, serverless, no SLA
   * - **Developer**: Development/test, no SLA, single region
   * - **Basic**: Production workloads, 99.95% SLA, 2 units max
   * - **Standard**: Production workloads, 99.95% SLA, 4 units max
   * - **Premium**: Enterprise workloads, 99.99% SLA, multi-region
   *
   * **Default**: Developer (non-prod), Consumption (production)
   */
  readonly sku?: 'Consumption' | 'Developer' | 'Basic' | 'Standard' | 'Premium';

  /**
   * Publisher email address
   *
   * @remarks
   * Required for API Management service creation.
   * Used for notifications and developer portal communication.
   *
   * **Default**: Derived from backend settings or 'noreply@{domain}'
   */
  readonly publisherEmail?: string;

  /**
   * Publisher name/organization
   *
   * @remarks
   * Displayed in developer portal and API documentation.
   *
   * **Default**: Derived from backend settings organization name
   */
  readonly publisherName?: string;

  /**
   * Enable virtual network integration
   *
   * @remarks
   * Only available for Developer, Premium SKUs.
   * Required for private API endpoints.
   *
   * **Default**: false
   */
  readonly enableVNet?: boolean;

  /**
   * Virtual network type
   *
   * @remarks
   * - **External**: Public IP with VNet-integrated backend
   * - **Internal**: Private IP accessible only within VNet
   *
   * Only applicable if enableVNet is true.
   *
   * **Default**: 'External'
   */
  readonly vnetType?: 'External' | 'Internal';
}

