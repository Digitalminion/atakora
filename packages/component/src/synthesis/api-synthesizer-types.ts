/**
 * API operation policy configuration
 *
 * @remarks
 * Defines policies applied to API operations including authentication,
 * rate limiting, and CORS. Policies are implemented as Azure API Management
 * policy XML snippets.
 *
 * **Policy Scope:**
 * - Service-level: Applied to all APIs
 * - API-level: Applied to all operations in an API
 * - Operation-level: Applied to a single operation
 *
 * Operation-level policies override API-level, which override service-level.
 *
 * @example
 * ```typescript
 * const policies: PolicyConfiguration = {
 *   authentication: {
 *     type: 'jwt',
 *     config: {
 *       issuer: 'https://login.microsoftonline.com/{tenantId}',
 *       audience: 'api://my-api'
 *     }
 *   },
 *   rateLimit: {
 *     calls: 100,
 *     renewalPeriod: 60
 *   },
 *   cors: {
 *     allowedOrigins: ['https://app.example.com'],
 *     allowedMethods: ['GET', 'POST', 'PUT', 'DELETE']
 *   }
 * };
 * ```
 */
export interface PolicyConfiguration {
  /**
   * Rate limiting policy
   *
   * @remarks
   * Limits the number of API calls within a time window.
   * Prevents abuse and ensures fair usage.
   *
   * **Implementation**: Uses API Management `rate-limit` policy
   */
  readonly rateLimit?: RateLimitPolicy;

  /**
   * Authentication policy
   *
   * @remarks
   * Validates authentication tokens before allowing API access.
   * Supports multiple authentication schemes.
   */
  readonly authentication?: AuthenticationPolicy;

  /**
   * CORS policy
   *
   * @remarks
   * Configures Cross-Origin Resource Sharing for browser-based clients.
   * Required for web applications making API calls from different domains.
   */
  readonly cors?: CorsPolicy;

  /**
   * IP filtering policy
   *
   * @remarks
   * Restricts API access to specific IP addresses or ranges.
   * Useful for internal APIs or partner integrations.
   */
  readonly ipFilter?: IpFilterPolicy;

  /**
   * Caching policy
   *
   * @remarks
   * Configures response caching to improve performance and reduce backend load.
   * Only applicable to GET operations.
   */
  readonly caching?: CachingPolicy;

  /**
   * Custom XML policy
   *
   * @remarks
   * Raw API Management policy XML for advanced scenarios.
   * Use this for policies not covered by typed configuration.
   *
   * **Warning**: No type safety or validation. Use with caution.
   */
  readonly customXml?: string;
}

