/**
 * API operation definition
 *
 * @remarks
 * Represents a single REST API operation in Azure API Management.
 * Each CRUD model generates 5 operations following REST conventions.
 *
 * **CRUD Operations Pattern:**
 * - **List**: GET /resources
 * - **Create**: POST /resources
 * - **Get**: GET /resources/{id}
 * - **Update**: PUT /resources/{id}
 * - **Delete**: DELETE /resources/{id}
 *
 * @example
 * ```typescript
 * const operation: ApiOperation = {
 *   operationId: 'getUser',
 *   method: 'GET',
 *   path: '/users/{id}',
 *   displayName: 'Get User by ID',
 *   description: 'Retrieve a single user by their unique identifier',
 *   policies: {
 *     authentication: {
 *       type: 'jwt',
 *       config: { issuer: 'https://login.microsoft.com', ... }
 *     },
 *     rateLimit: {
 *       calls: 100,
 *       renewalPeriod: 60
 *     }
 *   }
 * };
 * ```
 */
export interface ApiOperation {
  /**
   * Unique operation identifier
   *
   * @remarks
   * Used for operation lookup and OpenAPI operationId.
   *
   * **Naming Convention**: `{verb}{ModelName}`
   * - Examples: `listUsers`, `createUser`, `getUser`, `updateUser`, `deleteUser`
   */
  readonly operationId: string;

  /**
   * HTTP method
   *
   * @remarks
   * Standard REST HTTP methods aligned with CRUD operations:
   * - **GET**: Retrieve (list or get)
   * - **POST**: Create
   * - **PUT**: Update (full replacement)
   * - **PATCH**: Update (partial)
   * - **DELETE**: Delete
   */
  readonly method: 'GET' | 'POST' | 'PUT' | 'DELETE' | 'PATCH';

  /**
   * URL path template
   *
   * @remarks
   * Path may include template parameters in curly braces.
   *
   * **Examples:**
   * - `/users` (collection)
   * - `/users/{id}` (single resource)
   * - `/users/{userId}/posts/{postId}` (nested resource)
   */
  readonly path: string;

  /**
   * Human-readable operation name
   *
   * @remarks
   * Displayed in developer portal and API documentation.
   *
   * **Examples:**
   * - "List Users"
   * - "Create User"
   * - "Get User by ID"
   */
  readonly displayName: string;

  /**
   * Detailed operation description
   *
   * @remarks
   * Optional. Used for API documentation and developer portal.
   * Should explain the operation's purpose, parameters, and behavior.
   */
  readonly description?: string;

  /**
   * Operation policies
   *
   * @remarks
   * Defines authentication, rate limiting, CORS, and other policies
   * specific to this operation. If not specified, API-level or
   * service-level policies apply.
   */
  readonly policies?: PolicyConfiguration;

  /**
   * Backend service URL
   *
   * @remarks
   * The URL to which API Management will proxy requests.
   * Typically points to an Azure Function App endpoint.
   *
   * **Example**: `https://func-myapp-dev-eus-01.azurewebsites.net/api/{path}`
   */
  readonly backendUrl?: string;

  /**
   * Full REST operation definition
   *
   * @remarks
   * Optional reference to the complete IRestOperation for advanced scenarios
   * like OpenAPI generation. The synthesizer can use this for detailed
   * operation metadata, request/response schemas, etc.
   */
  readonly restOperation?: IRestOperation;
}

