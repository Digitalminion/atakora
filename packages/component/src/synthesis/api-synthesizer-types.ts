// API Synthesizer Interface
// ============================================================================

/**
 * Interface for API Synthesizer
 *
 * @remarks
 * The ApiSynthesizer generates Azure API Management resources from schema definitions.
 * It follows Amplify's approach of creating REST operations for each CRUD model:
 * - GET /users (list)
 * - POST /users (create)
 * - GET /users/{id} (get)
 * - PUT /users/{id} (update)
 * - DELETE /users/{id} (delete)
 *
 * The synthesizer orchestrates:
 * 1. API Management service creation (APIM instance)
 * 2. API creation (logical grouping within APIM)
 * 3. Operation generation (CRUD operations per model)
 * 4. Policy application (auth, rate limiting, CORS)
 *
 * @example
 * ```typescript
 * const synthesizer = new ApiSynthesizer();
 * const resources = await synthesizer.synthesize(
 *   schema,
 *   resourceGroup,
 *   dataResources
 * );
 *
 * // Access generated resources
 * console.log(resources.apim.serviceName);
 * console.log(resources.operations.length); // 5 per CRUD model
 * ```
 */
export interface ApiSynthesizer {
  /**
   * Synthesize API Management resources from schema
   *
   * @param schema - Schema object containing model definitions
   * @param stack - Resource group stack for CDK construct placement
   * @param dataResources - Backend resources (Cosmos, Function App, Storage) for API integration
   * @returns Promise resolving to generated API resources
   *
   * @throws {Error} If schema validation fails
   * @throws {Error} If APIM configuration is invalid
   * @throws {Error} If operation generation fails
   *
   * @remarks
   * The synthesize method performs the following phases:
   * 1. **Discovery**: Analyze schema to identify CRUD models
   * 2. **APIM Setup**: Create or reference API Management service
   * 3. **API Creation**: Create API within APIM
   * 4. **Operation Generation**: Generate CRUD operations for each model
   * 5. **Policy Application**: Apply authentication and rate limiting policies
   * 6. **Validation**: Ensure all resources are valid and deployable
   */
  synthesize(
    schema: SchemaObject,
    stack: ResourceGroupStack,
    dataResources: BackendDataResources
  ): Promise<ApiResources>;
}

