/**
 * Generated API resources
 *
 * @remarks
 * Contains all Azure API Management resources generated by the synthesizer:
 * - **apim**: The API Management service instance
 * - **api**: The API within APIM (logical grouping of operations)
 * - **operations**: All CRUD operations generated for models
 *
 * Each CRUD model generates 5 operations following REST conventions.
 *
 * **Null Values:**
 * Properties may be null to support placeholder implementations during
 * incremental development. Consumers should check for null before using.
 *
 * @example
 * ```typescript
 * const resources: ApiResources = {
 *   apim: apimService,
 *   api: backendApi,
 *   operations: [
 *     { operationId: 'listUsers', method: 'GET', path: '/users', ... },
 *     { operationId: 'createUser', method: 'POST', path: '/users', ... },
 *     { operationId: 'getUser', method: 'GET', path: '/users/{id}', ... },
 *     { operationId: 'updateUser', method: 'PUT', path: '/users/{id}', ... },
 *     { operationId: 'deleteUser', method: 'DELETE', path: '/users/{id}', ... },
 *   ]
 * };
 * ```
 */
export interface ApiResources {
  /**
   * API Management service instance
   *
   * @remarks
   * The top-level Azure API Management service that hosts all APIs and operations.
   * This is the CDK construct reference (IService interface).
   *
   * **Null in Placeholder Implementations:**
   * May be null during incremental development phases. Check before using.
   */
  readonly apim: IService | null;

  /**
   * API within APIM
   *
   * @remarks
   * Logical grouping of operations within the API Management service.
   * Typically one API per backend application.
   *
   * **Null in Placeholder Implementations:**
   * May be null during incremental development phases. Check before using.
   */
  readonly api: IServiceApi | null;

  /**
   * Generated API operations
   *
   * @remarks
   * Array of all CRUD operations generated for schema models.
   * Each operation includes method, path, policies, and backend configuration.
   */
  readonly operations: readonly ApiOperation[];
}

