/**
 * Backend data layer resources for API integration
 *
 * @remarks
 * Contains references to ALL backend resources (data storage, compute, and storage)
 * that APIs will integrate with. This is broader than {@link DataResources} from
 * data-synthesizer-types.ts which only contains Cosmos DB resources.
 *
 * These resources are typically generated by multiple synthesizers:
 * - DataSynthesizer: Cosmos DB account and database
 * - ComputeSynthesizer: Function App
 * - StorageSynthesizer: Storage Account
 *
 * The ApiSynthesizer receives these resources to configure backend URLs,
 * connection strings, and integration policies.
 *
 * @see {@link DataResources} from data-synthesizer-types.ts for Cosmos-only resources
 *
 * @example
 * ```typescript
 * const backendResources: BackendDataResources = {
 *   cosmosAccount: cosmosDbAccount,
 *   cosmosDatabase: cosmosDb,
 *   functionApp: functionAppService,
 *   storageAccount: storageAccount
 * };
 * ```
 */
export interface BackendDataResources {
  /**
   * Cosmos DB account
   *
   * @remarks
   * Reference to the Cosmos DB account for CRUD model storage.
   * Used to configure connection strings and backend integration.
   */
  readonly cosmosAccount?: IDatabaseAccount;

  /**
   * Cosmos DB database
   *
   * @remarks
   * Reference to the Cosmos DB database containing model containers.
   */
  readonly cosmosDatabase?: ICosmosDBDatabase;

  /**
   * Function App service
   *
   * @remarks
   * Reference to the Azure Function App that implements API logic.
   * The API Management operations will proxy to this Function App.
   */
  readonly functionApp?: ISite;

  /**
   * Storage Account
   *
   * @remarks
   * Reference to the Azure Storage Account for blob storage, queues, etc.
   */
  readonly storageAccount?: IStorageAccount;
}

